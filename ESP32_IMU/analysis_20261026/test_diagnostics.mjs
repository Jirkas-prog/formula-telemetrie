import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('./app/analysis_ui.js',import.meta.url),'utf8');
const elements={showbad:{checked:true},filtered:{checked:true,disabled:false},qualityMode:{textContent:''}};
let draws=0,stats=0;
const context=vm.createContext({$:id=>elements[id],manifest:{},meta:{digital_fault_fraction:1},viewCache:{clear(){}},draw(){draws++},scheduleAnalysis(){stats++}});
vm.runInContext(source.slice(0,source.indexOf('function prepareAnalysis')),context);
vm.runInContext('toggleDiagnosticView()',context);
assert.equal(elements.filtered.checked,false);assert.equal(elements.filtered.disabled,true);
assert.match(elements.qualityMode.textContent,/Diagnostický pohled/);
elements.showbad.checked=false;vm.runInContext('toggleDiagnosticView()',context);
assert.equal(elements.filtered.checked,true);assert.equal(elements.filtered.disabled,false);
context.manifest={csv:{schema:{filtered:false}}};elements.filtered.checked=false;
elements.showbad.checked=true;vm.runInContext('toggleDiagnosticView()',context);
elements.showbad.checked=false;vm.runInContext('toggleDiagnosticView()',context);
assert.equal(elements.filtered.checked,false);assert.equal(elements.filtered.disabled,true);
assert.equal(draws,4);assert.equal(stats,4);
console.log('PASS: diagnostic display exposes raw means, restores the filter, preserves CSV capabilities, refreshes statistics.');
